	private static string GenerateTypeScriptDeclarations()
	{
		Type marker = typeof(IScriptObject);
		Type[] types = marker.Assembly.GetTypes()
			.Where(type => (type.IsPublic || type.IsNestedPublic) && !type.IsGenericType && marker.IsAssignableFrom(type)
				&& type != typeof(BVSignal) && type != typeof(BVSignalConnection))
			.OrderBy(InheritanceDepth).ThenBy(type => type.FullName, StringComparer.Ordinal).ToArray();
		HashSet<Type> available = types.ToHashSet();
		StringBuilder output = new("// Generated by BrickVerse Creator. Do not edit.\n");
		output.AppendLine("declare interface Signal<T extends unknown[] = []> { Connect(callback: (...args: T) => void): unknown; }");
		foreach (Type type in types)
		{
			string parent = type.BaseType != null && available.Contains(type.BaseType) ? $" extends {TypeName(type.BaseType)}" : "";
			output.Append("declare class ").Append(TypeName(type)).Append(parent).AppendLine(" {");
			foreach (PropertyInfo property in type.GetProperties(BindingFlags.Instance | BindingFlags.Public | BindingFlags.DeclaredOnly))
			{
				if (property.GetCustomAttribute<ScriptPropertyAttribute>() == null) continue;
				output.Append("  ");
				if (property.SetMethod?.IsPublic != true) output.Append("readonly ");
				output.Append(property.Name).Append(": ").Append(TypeScriptType(property.PropertyType)).AppendLine(";");
			}
			foreach (MethodInfo method in type.GetMethods(BindingFlags.Instance | BindingFlags.Public | BindingFlags.DeclaredOnly))
			{
				ScriptMethodAttribute? attribute = method.GetCustomAttribute<ScriptMethodAttribute>();
				if (attribute == null || method.IsGenericMethod) continue;
				ParameterInfo[] parameters = method.GetParameters()
					.Where(parameter => parameter.GetCustomAttribute<ScriptingCallerAttribute>() == null
						&& parameter.ParameterType != typeof(BVCallback)).ToArray();
				output.Append("  ").Append(attribute.MethodName ?? method.Name).Append('(');
				for (int index = 0; index < parameters.Length; index++)
				{
					if (index > 0) output.Append(", ");
					ParameterInfo parameter = parameters[index];
					output.Append(parameter.Name ?? $"arg{index}");
					if (parameter.IsOptional) output.Append('?');
					output.Append(": ").Append(TypeScriptType(parameter.ParameterType));
				}
				output.Append("): ").Append(TypeScriptType(method.ReturnType)).AppendLine(";");
			}
			output.AppendLine("}");
		}

		foreach (Type type in types)
		{
			StaticAttribute? attribute = type.GetCustomAttribute<StaticAttribute>();
			if (attribute == null) continue;
			string name = string.IsNullOrWhiteSpace(attribute.Alias) ? type.Name : attribute.Alias!;
			output.Append("declare const ").Append(name).Append(": ").Append(TypeName(type)).AppendLine(";");
		}
		output.AppendLine("declare const game: World;");
		output.AppendLine("declare const world: World;");
		output.AppendLine("declare const script: { readonly Name: string };");
		output.AppendLine("declare function print(...values: unknown[]): void;");
		output.AppendLine("interface Console { log(...values: unknown[]): void; info(...values: unknown[]): void; warn(...values: unknown[]): void; error(...values: unknown[]): void; }");
		output.AppendLine("declare const console: Console;");
		return output.ToString();
	}

	private static string TypeScriptType(Type type)
	{
		Type raw = Nullable.GetUnderlyingType(type) ?? type;
		string suffix = raw == type ? "" : " | null";
		if (raw == typeof(void)) return "void";
		if (raw == typeof(string) || raw == typeof(char)) return "string" + suffix;
		if (raw == typeof(bool)) return "boolean" + suffix;
		if (raw.IsPrimitive || raw == typeof(decimal) || raw.IsEnum) return "number" + suffix;
		if (raw.IsArray) return $"{TypeScriptType(raw.GetElementType()!)}[]" + suffix;
		if (raw.IsGenericType && raw.GetGenericTypeDefinition().Name.StartsWith("BVSignal`", StringComparison.Ordinal))
			return $"Signal<[{string.Join(", ", raw.GetGenericArguments().Select(TypeScriptType))}]>" + suffix;
		if (raw == typeof(BVSignal)) return "Signal" + suffix;
		if (typeof(IScriptObject).IsAssignableFrom(raw)) return TypeName(raw) + suffix;
		if (typeof(System.Threading.Tasks.Task).IsAssignableFrom(raw))
			return raw.IsGenericType ? $"Promise<{TypeScriptType(raw.GetGenericArguments()[0])}>" : "Promise<void>";
		return "unknown" + suffix;
	}

	private static string TypeName(Type type) => (type.IsNested && type.DeclaringType != null
		? type.DeclaringType.Name + "_" + type.Name
		: type.Name).Replace('`', '_').Replace('+', '_');
	private static int InheritanceDepth(Type type) { int depth = 0; for (Type? current = type.BaseType; current != null; current = current.BaseType) depth++; return depth; }
	private static void WriteIfMissing(string path, string content) { if (!File.Exists(path)) File.WriteAllText(path, content); }
}
