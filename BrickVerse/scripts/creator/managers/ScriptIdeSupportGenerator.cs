/// <summary>Generates IDE inputs from the authoritative runtime scripting metadata.</summary>
internal static class ScriptIdeSupportGenerator
{
	public static void Generate(string projectRoot)
	{
		string ideRoot = Path.Combine(projectRoot, ".bvproject", "ide");
		string includeRoot = Path.Combine(ideRoot, "include");
		Directory.CreateDirectory(includeRoot);

		File.WriteAllText(Path.Combine(ideRoot, "BrickVerse.Generated.cs"), CSharpBindingGenerator.Generate());
		File.WriteAllText(Path.Combine(ideRoot, "brickverse.d.ts"), GenerateTypeScriptDeclarations());
		File.WriteAllText(Path.Combine(includeRoot, "brickverse.h"), CppProvider.HeaderSource);
		File.WriteAllText(Path.Combine(ideRoot, "BrickVerseScripts.csproj"), GenerateCSharpProject());
		File.WriteAllText(Path.Combine(projectRoot, "BrickVerseScripts.sln"), GenerateSolution());
		WriteIfMissing(Path.Combine(projectRoot, "tsconfig.json"), GenerateTypeScriptConfig());
		WriteIfMissing(Path.Combine(projectRoot, ".clangd"), GenerateClangdConfig());
	}

	private static string GenerateCSharpProject()
	{
		string assembly = SecurityElement.Escape(typeof(BrickVerseScript).Assembly.Location) ?? "BrickVerse.dll";
		return $$"""
<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
