    <Compile Include="BrickVerse.Generated.cs" />
    <Reference Include="BrickVerse">
      <HintPath>{{assembly}}</HintPath>
      <Private>false</Private>
    </Reference>
  </ItemGroup>
</Project>
""";
	}

